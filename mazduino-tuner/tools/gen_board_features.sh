#!/usr/bin/env bash
# gen_board_features.sh - write boards/FEATURES.md from the defines each board sets.
#
# Usage (from the mazduino-fw repo root):
#   mazduino-tuner/tools/gen_board_features.sh [out_file]   # default: boards/FEATURES.md

set -euo pipefail
export LC_ALL=C

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT="${1:-$ROOT/boards/FEATURES.md}"

BASE="mazduino-compact mazduino-lite mazduino-core mazduino-mini6ch mazduino-mega100 mazduino-mega100-512"

# Label | defines that must all be on, each as NAME=firmware default.
ROWS='Electronic throttle (ETB)|ts_show_etb=true,EFI_ELECTRONIC_THROTTLE_BODY=TRUE
Traction control|ts_show_traction_control=true
Software knock|ts_show_software_knock=false,EFI_SOFTWARE_KNOCK=FALSE
Boost control|EFI_BOOST_CONTROL=TRUE
Launch control|EFI_LAUNCH_CONTROL=TRUE
Anti-lag|EFI_ANTILAG_SYSTEM=TRUE
VVT control|EFI_VVT_PID=TRUE,ts_show_vvt_output=true
Vehicle speed|EFI_VEHICLE_SPEED=TRUE
Lua scripts and user tables|EFI_LUA=TRUE
SD card logging|ts_show_sd_card=true,EFI_FILE_LOGGING=TRUE
Alternator control|EFI_ALTERNATOR_CONTROL=TRUE,ts_show_alternator=true
Main relay control|EFI_MAIN_RELAY_CONTROL=TRUE,ts_show_main_relay=true
GDI high pressure pump|EFI_HPFP=TRUE,ts_show_gdi=false
Stepper idle valve|ts_show_idle_stepper=true
Automatic transmission (TCU)|EFI_TCU=FALSE,ts_show_tcu=false'

name() { echo "${1#mazduino-}"; }

value() { # value <flags file> <NAME> <default>
	awk -v n="$2" -v d="$3" '$1 == n { print $2; found = 1 } END { if (!found) print d }' "$1"
}

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
for b in $BASE mazduino-compact-bigfuel mazduino-lite-bigfuel mazduino-core-bigfuel mazduino-mini6ch-bigfuel; do
	"$HERE/board_flags.sh" "$b" > "$TMP/$b"
done

{
	echo "# Features per board"
	echo
	echo "Generated by \`mazduino-tuner/tools/gen_board_features.sh\` from what each board sets in \`board.mk\`, \`efifeatures.h\` and \`prepend.txt\`. Do not edit by hand."
	echo
	echo "This table describes the firmware: a feature marked \`-\` is not built or not offered on that board. It says nothing about wiring, which is in each board's manual."
	echo
	echo "On Core the second CAN channel also needs its jumper set, and knock is in the firmware but the 48-pin carrier connector does not bring it out."
	echo
	echo "Software knock is off by default on every board that has it. Turn it on in the tune."
	echo
	printf '| Feature |'
	for b in $BASE; do printf ' %s |' "$(name "$b")"; done
	echo
	printf '|---|'
	for b in $BASE; do printf -- '---|'; done
	echo
	while IFS='|' read -r label defs; do
		printf '| %s |' "$label"
		for b in $BASE; do
			on=yes
			for d in $(echo "$defs" | tr ',' ' '); do
				v="$(value "$TMP/$b" "${d%%=*}" "${d#*=}")"
				case "$v" in false|FALSE) on=- ;; esac
			done
			printf ' %s |' "$on"
		done
		echo
	done <<< "$ROWS"
	# CAN channels: the pins the board assigns. The firmware has CAN on every board.
	printf '| CAN bus channels |'
	for b in $BASE; do
		cfg="$ROOT/boards/$b/board_configuration.cpp"
		n=0
		grep -q 'canTxPin[[:space:]]*=' "$cfg" && n=$((n + 1))
		grep -q 'can2TxPin[[:space:]]*=' "$cfg" && n=$((n + 1))
		printf ' %s |' "$n"
	done
	echo
	printf '| Cylinders, wasted spark |'
	for b in $BASE; do
		max=12
		for n in 12 11 10 9 8 7 6 5; do
			[ "$(value "$TMP/$b" "ts_show_cylinder_$n" true)" = "false" ] && max=$((n - 1))
		done
		printf ' %s |' "$max"
	done
	echo
	printf '| VVT target table |'
	for b in $BASE; do
		s="$(value "$TMP/$b" VVT_TABLE_SIZE 8)"
		printf ' %sx%s |' "$s" "$s"
	done
	echo
	printf '| TunerStudio over Bluetooth (serial port) |'
	for b in $BASE; do
		if [ -n "$(value "$TMP/$b" TS_SECONDARY_UxART_PORT "")$(value "$TMP/$b" TS_PRIMARY_UxART_PORT "")" ]; then
			printf ' yes |'
		else
			printf ' - |'
		fi
	done
	echo
	echo
	echo "## BIGFUEL variants"
	echo
	echo "Same hardware and features as the board they are named after, except:"
	echo
	echo '| | Base board | BIGFUEL |'
	echo '|---|---|---|'
	b=mazduino-mini6ch-bigfuel
	echo "| VE table | 16x16 | $(value "$TMP/$b" VE_LOAD_COUNT 16)x$(value "$TMP/$b" VE_RPM_COUNT 16) |"
	echo "| Ignition table | 16x16 | $(value "$TMP/$b" IGN_LOAD_COUNT 16)x$(value "$TMP/$b" IGN_RPM_COUNT 16) |"
	sniffer=yes
	[ "$(value "$TMP/$b" EFI_ENGINE_SNIFFER TRUE)" = "FALSE" ] && sniffer=-
	echo "| Engine sniffer | yes | $sniffer |"
	echo
	echo "Tunes are not interchangeable between a board and its BIGFUEL variant."
	echo
	echo "Boards with a BIGFUEL variant: compact, core, lite, mini6ch."
} > "$OUT"
